#!/usr/bin/env python3
"""Validate every module of this repo (doc/contract.md section 5).

A thin wrapper: the module.properties rules come from xewe-os-tools (`xewe.modules.registry.validate`);
this file adds only the repo-policy rules. Run it with a Python that has xewe-os-tools
installed, which is a harness venv:

    <harness>/build/tools/.venv/bin/python tools/validate.py [--harness DIR]
    <harness>/build/tools/.venv/bin/python tools/validate.py --write-index

Output: one `error|warning: <where>: <message>` line per finding, then
`N modules, E errors, W warnings`. Exit 0 no errors, 1 errors, 2 usage error, 3 tools missing.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
import tomllib
from pathlib import Path

EXIT_OK, EXIT_FAIL, EXIT_USAGE, EXIT_NOT_SETUP = 0, 1, 2, 3

REPO = Path(__file__).resolve().parents[1]
INDEX = "doc/modules.md"
CATALOGUE = "libraries.toml"
REPO_URL = "https://github.com/xewe-labs/xewe-os-modules/tree/main/modules/{slug}"
LIBRARY_RE = re.compile(r"^[A-Za-z0-9_.\- ]+$")
FORBIDDEN_LIBRARIES = {"XeWeCore", "XeWeOS"}
# old API and the arduino-esp32 `cli()` macro; checked in every file of src/<folder>/
FORBIDDEN_SOURCE = (
    (
        re.compile(r"\bcli\s*\("),
        "'cli(' (arduino-esp32 defines cli() as a macro; use os.cli.execute)",
    ),
    (re.compile(r"<XeWeOS\.h>"), "'<XeWeOS.h>' (include <XeWeCore.h>)"),
    (re.compile(r"xewe::os::"), "'xewe::os::' (old namespace; use xewe::)"),
    (
        re.compile(r"ModuleController"),
        "'ModuleController' (old API; take xewe::Os& host)",
    ),
    (re.compile(r"\bcontroller\b"), "'controller' (old API; use the member os)"),
    (re.compile(r"xewe_cli"), "'xewe_cli' (old API; use os.cli)"),
    (re.compile(r"this->os\b"), "'this->os' (use os)"),
    (re.compile(r"std::span"), "'std::span' (use xewe::span)"),
)
# core 2.1 features: a module that uses them must require core >= 2.1.0 (rule core21)
CORE21_RE = re.compile(r"\b(SettingDef|ListenerSet|SchemaOut)\b|xewe::pins::")
SETTING_KEY_RE = re.compile(r"xewe::setting<[^>]*>\s*\(\s*\"([^\"]*)\"")
REQUIRES_MIN_RE = re.compile(r">=\s*(\d+)\.(\d+)\.(\d+)")

INDEX_HEADER = (
    "<!-- Generated by `tools/validate.py --write-index`; do not edit. -->\n"
    "# Modules\n"
    "\n"
    "| Slug | Name | Id | Version | Description | Depends on | Requires core |\n"
    "|---|---|---|---|---|---|---|\n"
)


class Problem:
    """Same shape and `str()` as xewe.modules.registry.Problem."""

    def __init__(self, where: str, message: str, error: bool = True) -> None:
        self.where, self.message, self.error = where, message, error

    def __str__(self) -> str:
        return f"{'error' if self.error else 'warning'}: {self.where}: {self.message}"


def render_index(registry) -> str:
    rows = []
    for m in registry.all:
        p = m.props
        deps = ", ".join(m.deps) or "-"
        cells = [
            f"[`{m.slug}`](../modules/{m.dir.name})",
            p.get("name", ""),
            f"`{p.get('id', '')}`",
            p.get("version", ""),
            p.get("description", ""),
            deps,
            f"`{p.get('requires_core', '')}`",
        ]
        rows.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |\n")
    return INDEX_HEADER + "".join(rows)


def _string_literal(text: str, value: str) -> bool:
    return f'"{value}"' in text


def check_tests(path: Path, err) -> None:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    except SyntaxError as exc:
        err(f"tests: {path.name} does not parse: {exc.msg} (line {exc.lineno})")
        return
    names = {
        n.name
        for n in tree.body
        if isinstance(n, ast.FunctionDef) and n.name.startswith("test_")
    }
    for required in ("test_compiles", "test_status"):
        if required not in names:
            err(f"tests: {required} missing in {path.name}")
    if not names - {"test_compiles", "test_status"}:
        err(
            f"tests: {path.name} needs at least one behaviour test besides test_compiles and test_status"
        )


TEST_FOLDERS = ("board", "unit")
"""The only entries allowed under a module's tests/: board/ (required) and unit/ (optional)."""


def check_tests_layout(tests: Path, err) -> None:
    """tests/ holds exactly board/ and optionally unit/; no conftest.py or __init__.py in either."""
    if not tests.is_dir():
        return
    for entry in sorted(tests.iterdir()):
        if entry.name == "__pycache__":
            continue
        if entry.name not in TEST_FOLDERS or not entry.is_dir():
            err(
                f"files: tests/{entry.name} not allowed (tests/ holds only board/ and unit/)"
            )
    for sub in TEST_FOLDERS:
        for name in ("conftest.py", "__init__.py"):
            if (tests / sub / name).exists():
                err(
                    f"files: tests/{sub}/{name} not allowed (the plugin provides the fixtures)"
                )


def read_catalogue() -> set[str]:
    """Library names pinned in libraries.toml (empty when the file is missing)."""
    path = REPO / CATALOGUE
    return (
        set(tomllib.loads(path.read_text(encoding="utf-8")))
        if path.is_file()
        else set()
    )


def check_module(
    m,
    libraries: set[str] | None,
    catalogue: frozenset[str] | set[str] = frozenset(),
    owners: dict[str, str] | None = None,
) -> list[Problem]:
    problems: list[Problem] = []
    where = m.slug or m.dir.name

    def err(msg: str, error: bool = True) -> None:
        problems.append(Problem(where, msg, error))

    p = m.props
    folder = p.get("folder", "")
    src = m.dir / "src" / folder
    header, cpp = src / f"{folder}.h", src / f"{folder}.cpp"

    # files
    for f in (
        header,
        cpp,
        m.dir / "README.md",
        m.dir / "tests" / "board" / f"test_{m.slug}.py",
    ):
        if not f.is_file():
            err(f"files: {f.relative_to(m.dir)} missing")
    if p.get("include", "") != f"src/{folder}/{folder}.h":
        err(f"files: include '{p.get('include', '')}' must be src/{folder}/{folder}.h")
    check_tests_layout(m.dir / "tests", err)

    # class, declare-os
    decl = m.declared()
    if decl is not None:
        dtype, _var, args = decl
        if dtype != folder:
            err(f"class: declare type '{dtype}' must equal folder '{folder}'")
        if not args or args[0] != "os":
            err(
                f"declare-os: first declare argument must be 'os', got '{args[0] if args else ''}'"
            )

    # name, id-source
    cpp_text = cpp.read_text(encoding="utf-8") if cpp.is_file() else ""
    if cpp_text:
        if not _string_literal(cpp_text, p.get("name", "")):
            err(
                f"name: '\"{p.get('name', '')}\"' not found in {cpp.name} (must equal the C++ name argument)"
            )
        if not _string_literal(cpp_text, p.get("id", "")):
            err(f"id-source: '\"{p.get('id', '')}\"' not found in {cpp.name}")

    # tests
    test_file = m.dir / "tests" / "board" / f"test_{m.slug}.py"
    if test_file.is_file():
        check_tests(test_file, err)

    # repo
    want = REPO_URL.format(slug=m.slug)
    if p.get("repo", "") != want:
        err(f"repo '{p.get('repo', '')}' must be {want}")

    # depends_libraries
    for lib in (x.strip() for x in p.get("depends_libraries", "").split(",")):
        if not lib:
            continue
        if not LIBRARY_RE.match(lib):
            err(f"depends_libraries: '{lib}' must match {LIBRARY_RE.pattern}")
        elif lib in FORBIDDEN_LIBRARIES:
            err(
                f"depends_libraries: '{lib}' must not be listed (XeWeCore comes from the harness)"
            )
        elif libraries is not None and lib not in libraries and lib not in catalogue:
            err(
                f"depends_libraries: '{lib}' is neither in {CATALOGUE} nor in the harness xewe.toml [libraries]"
            )
        elif lib not in catalogue:
            err(
                f"depends_libraries: '{lib}' is not in {CATALOGUE} (xewe setup will not install it)",
                error=False,
            )

    # source
    if src.is_dir():
        for f in sorted(x for x in src.rglob("*") if x.is_file()):
            text = f.read_text(encoding="utf-8", errors="replace")
            for n, line in enumerate(text.splitlines(), 1):
                for rx, what in FORBIDDEN_SOURCE:
                    if rx.search(line):
                        err(f"source: {f.relative_to(m.dir)}:{n}: {what}")
        if header.is_file() and "#include <XeWeCore.h>" not in header.read_text(
            encoding="utf-8"
        ):
            err(f"source: {header.name} must contain '#include <XeWeCore.h>'")
        check_core21(src, p.get("requires_core", ""), err)
        check_config(src, m.slug, err, owners)

    # stray (inside the module)
    for f in sorted(m.dir.rglob("*.ino")):
        err(
            f"stray: {f.relative_to(m.dir)} (validation sketches are replaced by tests)"
        )
    for name in ("scripts", "LICENSE.txt"):
        if (m.dir / name).exists():
            err(f"stray: {name} (one LICENSE.txt for the repo; no per-module scripts)")
    return problems


SECTIONS = ("default runtime values", "compile time defined constants")
CONFIG_MARKERS = tuple(
    f"/* ---- {kind} {name} ---- */" for name in SECTIONS for kind in ("start", "end")
)
"""The four section markers of a module Config.h (XeWeCore doc/config.md), in this order: start
and end of the default runtime values, start and end of the compile time defined constants."""
EXPECTED_MARKERS = "expected lines " + ", ".join(f"'{m}'" for m in CONFIG_MARKERS)
LEGACY_MARKERS = {f"/* ---- {name} ---- */" for name in SECTIONS}
RUNTIME, CONSTANTS, FIRST_BOOT = range(3)
"""The two sections; FIRST_BOOT is not a section but the runtime values that define NAME_PROMPT."""
MARKER_LIKE_RE = re.compile(r"^/\*\s*----.*----\s*\*/$")
CONFIG_SPDX_LINES = 3
RESERVED_PREFIXES = {
    "XEWE_CORE_": "core",
    "XEWE_CHIP_": "the build",
    "XEWE_TEST_": "the tools",
}
PROMPT = "_PROMPT"
CONFIG_DIRECTIVE_RE = re.compile(r"^#\s*(\w+)\s*(.*)$")
DEFINE_RE = re.compile(r"^#\s*(define|undef)\s+([A-Za-z_]\w*)")
PROMPT_TEST_RE = re.compile(
    r"^#\s*(?:ifdef|ifndef)\s+(\w+_PROMPT)\b|\bdefined\s*\(?\s*(\w+_PROMPT)\b", re.M
)
SETTING_CALL_RE = re.compile(r"xewe::setting<")
SETTING_FLAGS = "xewe::SettingDef::"
# arguments of a settings row without the flags: bool 3, string 4, number 5; index of the default
ROW_DEFAULT_INDEX = {3: 1, 4: 2, 5: 3}


def config_prefix(slug: str) -> str:
    """`XEWE_<SLUG>_`: the slug in upper case with `-` as `_`."""
    return "XEWE_" + slug.upper().replace("-", "_") + "_"


def config_owners(slugs) -> dict[str, str]:
    """Every define prefix and who owns it: each module's, plus the core's."""
    owners = {config_prefix(s): s for s in slugs}
    owners["XEWE_CORE_"] = "core"
    return owners


def owner_of(name: str, owners: dict[str, str]) -> str | None:
    """The owner of the longest prefix that starts `name` (XEWE_LED_WEB_X is led-web's, not led's)."""
    best = max((p for p in owners if name.startswith(p)), key=len, default=None)
    return owners[best] if best else None


def _call_args(text: str, open_idx: int) -> list[str] | None:
    """The top-level arguments of the call whose `(` is at open_idx, string and char literals and
    nested brackets respected; None when the call is not closed."""
    args, cur, depth, i = [], [], 0, open_idx + 1
    while i < len(text):
        c = text[i]
        if c in "\"'":
            j = i + 1
            while j < len(text) and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            cur.append(text[i : j + 1])
            i = j + 1
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                args.append("".join(cur).strip())
                return [] if args == [""] else args
            depth -= 1
        elif c == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
            i += 1
            continue
        cur.append(c)
        i += 1
    return None


def setting_rows(text: str) -> list[tuple[str, str | None, int]]:
    """Every `xewe::setting<&X::m>(...)` row as (key, default argument, line); the default is None
    when the row cannot be read."""
    rows = []
    for m in SETTING_CALL_RE.finditer(text):
        depth, i = 1, m.end()
        while i < len(text) and depth:
            depth += {"<": 1, ">": -1}.get(text[i], 0)
            i += 1
        while i < len(text) and text[i].isspace():
            i += 1
        if i >= len(text) or text[i] != "(":
            continue
        args = _call_args(text, i)
        line = text.count("\n", 0, m.start()) + 1
        if not args:
            rows.append(("", None, line))
            continue
        if args[-1].startswith(SETTING_FLAGS):
            args = args[:-1]
        key = args[0].strip('"') if args[0].startswith('"') else ""
        index = ROW_DEFAULT_INDEX.get(len(args))
        rows.append((key, args[index] if index is not None else None, line))
    return rows


def parse_config(
    lines: list[str], prefix: str, owners: dict[str, str], err
) -> dict[int, set[str]]:
    """Check one module Config.h and return its names per section (RUNTIME, CONSTANTS) and, as
    FIRST_BOOT, the runtime names whose group defines `<NAME>_PROMPT 1`."""
    names: dict[int, set[str]] = {RUNTIME: set(), CONSTANTS: set(), FIRST_BOOT: set()}
    name_re = re.compile(rf"^{re.escape(prefix)}[A-Z0-9_]+$")
    section = -1
    in_group = False  # between a start marker and its end marker
    seen_markers: list[str] = []
    stack: list[
        str | None
    ] = []  # the group name at depth 0, None for rejected conditionals
    in_block = False  # inside the multi-line header comment

    def is_comment(n: int) -> bool:
        text = lines[n - 1].strip() if 1 <= n <= len(lines) else ""
        return text.endswith("*/") and text not in CONFIG_MARKERS

    for n, line in enumerate(lines, 1):
        text = line.strip()
        if in_block:
            in_block = "*/" not in text
            continue
        if not text:
            continue
        if section >= 0 and not in_group and text not in CONFIG_MARKERS:
            err(
                f"config: Config.h:{n}: only blank lines between an end marker and the next "
                "start marker, or after the last end marker"
            )
        if text.startswith("//"):
            if n > CONFIG_SPDX_LINES:
                if "----" in text or any(name in text for name in SECTIONS):
                    err(
                        f"config: Config.h:{n}: the '//' section marker form is gone; "
                        f"{EXPECTED_MARKERS}"
                    )
                else:
                    err(
                        f"config: Config.h:{n}: no '//' line (only the {CONFIG_SPDX_LINES} SPDX "
                        "header lines; every other text is a /* ... */ comment)"
                    )
            continue
        if text.startswith("/*"):
            if text in CONFIG_MARKERS:
                if text in seen_markers:
                    err(f"config: Config.h:{n}: marker '{text}' appears twice")
                elif CONFIG_MARKERS.index(text) != len(seen_markers):
                    err(f"config: Config.h:{n}: marker '{text}' out of order")
                seen_markers.append(text)
                index = CONFIG_MARKERS.index(text)
                section = index // 2
                in_group = index % 2 == 0
                if stack:
                    err(f"config: Config.h:{n}: marker '{text}' inside a conditional")
            elif text in LEGACY_MARKERS:
                err(
                    f"config: Config.h:{n}: single section marker '{text}'; {EXPECTED_MARKERS}"
                )
            elif MARKER_LIKE_RE.match(text):
                err(
                    f"config: Config.h:{n}: unknown section marker '{text}'; {EXPECTED_MARKERS}"
                )
            elif "*/" not in text:
                if in_group:
                    err(
                        f"config: Config.h:{n}: a comment below the header must be one "
                        "single-line /* ... */"
                    )
                in_block = True
            elif not text.endswith("*/") or text.count("*/") > 1:
                err(
                    f"config: Config.h:{n}: a comment line is one /* ... */ and nothing else"
                )
            continue
        directive = CONFIG_DIRECTIVE_RE.match(text)
        if not directive:
            err(
                f"config: Config.h:{n}: only comment and preprocessor lines are allowed"
            )
            continue
        kind, rest = directive.group(1), directive.group(2).split("//")[0].strip()
        if kind == "include":
            err(
                f"config: Config.h:{n}: no #include (the file must stay pure preprocessor)"
            )
        elif kind == "pragma":
            if rest != "once":
                err(f"config: Config.h:{n}: only '#pragma once' is allowed")
        elif kind == "ifndef" and not stack:
            name = rest.split()[0] if rest else ""
            stack.append(name)
            if section < 0:
                err(
                    f"config: Config.h:{n}: #ifndef {name} before the first start marker"
                )
            owner = owner_of(name, owners)
            if not name_re.match(name):
                err(
                    f"config: Config.h:{n}: '{name}' must match {prefix}<PARAM> ([A-Z0-9_]+)"
                )
            elif owner != owners[prefix]:
                err(
                    f"config: Config.h:{n}: '{name}' has the prefix of {owner}, not {prefix}"
                )
            elif name.endswith(PROMPT):
                err(f"config: Config.h:{n}: '{name}': the suffix {PROMPT} is reserved")
            elif in_group:
                names[section].add(name)
            if not is_comment(n - 1) or is_comment(n - 2):
                err(
                    f"config: Config.h:{n}: #ifndef {name} needs exactly one single-line "
                    "/* ... */ comment above it"
                )
            elif not lines[n - 2].strip().startswith("/*"):
                err(
                    f"config: Config.h:{n}: the comment above #ifndef {name} must be a "
                    "single-line /* ... */"
                )
        elif kind in ("ifndef", "ifdef", "if"):
            if kind == "ifndef" and stack:
                err(
                    f"config: Config.h:{n}: #ifndef {rest.split()[0] if rest else ''} nested "
                    f"inside the #ifndef {stack[0]} group"
                )
            else:
                err(
                    f"config: Config.h:{n}: #{kind} is not allowed in Config.h (a value that "
                    "differs per board is set by the project)"
                )
            stack.append(None)  # keeps the matching #endif from raising a second error
        elif kind in ("elif", "else"):
            err(f"config: Config.h:{n}: #{kind} is not allowed in Config.h")
        elif kind == "endif":
            if stack:
                stack.pop()
            else:
                err(f"config: Config.h:{n}: #endif without #if")
        elif kind == "define":
            name = rest.split()[0] if rest else ""
            group = stack[0] if stack else None
            if group is None:
                err(
                    f"config: Config.h:{n}: #define {name} must sit inside #ifndef {name}"
                )
            elif name == group:
                pass
            elif name == group + PROMPT:
                value = rest[len(name) :].strip()
                if not in_group or section != RUNTIME:
                    err(
                        f"config: Config.h:{n}: {name} outside the default runtime values section"
                    )
                elif len(stack) != 1 or value != "1":
                    err(
                        f"config: Config.h:{n}: {name} must be '#define {name} 1' in its group"
                    )
                else:
                    names[FIRST_BOOT].add(group)
            else:
                err(
                    f"config: Config.h:{n}: #define {name} must sit inside #ifndef {name}"
                )
        else:
            err(f"config: Config.h:{n}: #{kind} is not allowed in Config.h")
    if stack:
        err("config: Config.h: unclosed #ifndef group")
    if in_block:
        err("config: Config.h: unclosed /* comment")
    for marker in CONFIG_MARKERS:
        if marker not in seen_markers:
            err(f"config: Config.h: marker '{marker}' missing")
    return names


def check_config(
    src: Path, slug: str, err, owners: dict[str, str] | None = None
) -> None:
    """Rule config (XeWeCore doc/config.md). The module prefix is `XEWE_<SLUG>_`, clear of the
    reserved XEWE_CORE_, XEWE_CHIP_ and XEWE_TEST_. `src/<Folder>/Config.h`, when present, is pure
    preprocessor without includes: the four section markers `/* ---- start default runtime values
    ---- */`, `/* ---- end default runtime values ---- */`, `/* ---- start compile time defined
    constants ---- */` and `/* ---- end compile time defined constants ---- */` once each, in this
    order, outside any conditional; every group between a start and its end marker, nothing but
    blank lines between an end and the next start or after the last end (a section may be empty);
    the single-marker and the `//` forms are errors; no `//` line except the three SPDX header lines, every other text a
    `/* ... */` comment (the header paragraph one multi-line block, every other comment one line);
    every define inside `#ifndef` of its own name, with exactly one single-line comment above the
    `#ifndef`; names with the module prefix (longest-prefix ownership: XEWE_LED_WEB_* is led-web's);
    a value the first boot asks for is a default runtime value whose group holds
    `#define <NAME>_PROMPT 1` (inferred from that line; only in a group of the default runtime
    values section). Outside Config.h no source defines or undefines a name of any module's prefix or XEWE_CORE_. Every
    settings row's default is exactly `XEWE_<SLUG>_<KEY>`, a define of the default runtime values
    section; a module with rows has a Config.h. Every NAME with a `NAME_PROMPT` define is tested as
    `NAME_PROMPT` in the sources, and every `*_PROMPT` tested there is such a NAME of this module."""
    prefix = config_prefix(slug)
    owners = dict(owners or config_owners([slug]))
    owners.setdefault(prefix, slug)
    for reserved, who in RESERVED_PREFIXES.items():
        if prefix.startswith(reserved) or reserved.startswith(prefix):
            err(
                f"config: prefix {prefix} collides with {reserved} (reserved for {who})"
            )
    config = src / "Config.h"
    names = {RUNTIME: set(), CONSTANTS: set(), FIRST_BOOT: set()}
    if config.is_file():
        lines = config.read_text(encoding="utf-8", errors="replace").splitlines()
        names = parse_config(lines, prefix, owners, err)
    rows: list[tuple[str, str, str | None, int]] = []
    tested: set[str] = set()
    for f in sorted(x for x in src.rglob("*") if x.is_file() and x != config):
        text = f.read_text(encoding="utf-8", errors="replace")
        where = f.relative_to(src.parent.parent)
        for n, line in enumerate(text.splitlines(), 1):
            define = DEFINE_RE.match(line.strip())
            owner = owner_of(define.group(2), owners) if define else None
            if owner is not None:
                verb = "defined" if define.group(1) == "define" else "undefined"
                err(
                    f"config: {where}:{n}: '{define.group(2)}' is {verb} outside Config.h "
                    f"(a {owner} name)"
                )
        if f.suffix in (".h", ".hpp", ".cpp", ".tpp"):
            rows.extend((str(where), *row) for row in setting_rows(text))
            tested.update(a or b for a, b in PROMPT_TEST_RE.findall(text))
    if rows and not config.is_file():
        err("config: settings rows need src/<Folder>/Config.h with their defaults")
    stored = names[RUNTIME]
    for where, key, default, n in rows:
        want = prefix + key.upper()
        if default is None:
            err(
                f"config: {where}:{n}: settings row '{key}' not readable (bool, string or number)"
            )
        elif default != want:
            err(
                f"config: {where}:{n}: settings row '{key}' default must be {want}, got '{default}'"
            )
        elif config.is_file() and want not in stored:
            err(
                f"config: {where}:{n}: {want} is not a define of the default runtime values section"
            )
    for name in sorted(names[FIRST_BOOT]):
        if name + PROMPT not in tested:
            err(
                f"config: {name} defines {name}{PROMPT} but is never asked under #ifdef {name}{PROMPT}"
            )
    for name in sorted(tested):
        if name[: -len(PROMPT)] not in names[FIRST_BOOT]:
            err(
                f"config: {name} is tested, but no default runtime value of Config.h defines it"
            )


def check_core21(src: Path, requires_core: str, err) -> None:
    """Rule core21: core 2.1 features need requires_core >= 2.1.0; setting keys are valid NVS keys."""
    uses: set[str] = set()
    keys: list[tuple[str, str]] = []
    for f in sorted(
        x
        for x in src.rglob("*")
        if x.is_file() and x.suffix in (".h", ".hpp", ".cpp", ".tpp")
    ):
        text = f.read_text(encoding="utf-8", errors="replace")
        uses.update(m.group(0) for m in CORE21_RE.finditer(text))
        keys.extend((f.name, k) for k in SETTING_KEY_RE.findall(text))
    if uses:
        m = REQUIRES_MIN_RE.search(requires_core)
        if not m or tuple(int(x) for x in m.groups()) < (2, 1, 0):
            err(
                f"core21: uses {', '.join(sorted(uses))}, so requires_core must start at >=2.1.0 "
                f"(got '{requires_core}')"
            )
    seen: set[str] = set()
    for fname, key in keys:
        if not key or len(key) > 15 or re.search(r"[\s\"\\]", key):
            err(
                f"core21: {fname}: setting key '{key}' must be 1-15 characters, no whitespace, quote or backslash"
            )
        if key in seen:
            err(f"core21: {fname}: setting key '{key}' declared twice")
        seen.add(key)


def check_repo(registry) -> list[Problem]:
    problems: list[Problem] = []
    modules_dir = REPO / "modules"
    allowed = {
        m.dir / "module.properties" for m in registry.all if m.dir.parent == modules_dir
    }
    for f in sorted(REPO.rglob("module.properties")):
        if f not in allowed and ".git" not in f.parts:
            problems.append(
                Problem(
                    "repo",
                    f"stray: {f.relative_to(REPO)} (only modules/<slug>/module.properties)",
                )
            )
    for f in sorted(REPO.rglob("*.ino")):
        if ".git" not in f.parts and modules_dir not in f.parents:
            problems.append(Problem("repo", f"stray: {f.relative_to(REPO)}"))
    for base in (REPO, modules_dir):
        for d in sorted(base.glob("xewe-os-module-*")):
            problems.append(
                Problem(
                    "repo",
                    f"stray: {d.relative_to(REPO)}/ (old layout; use modules/<slug>/)",
                )
            )
    return problems


def read_harness(path: Path) -> tuple[str | None, set[str]]:
    manifest = path / "xewe.toml"
    if not manifest.is_file():
        raise SystemExit(f"usage: --harness {path}: no xewe.toml there")
    data = tomllib.loads(manifest.read_text(encoding="utf-8"))
    return data.get("core", {}).get("ref"), set(data.get("libraries", {}))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Validate the modules of this repo (doc/contract.md section 5)."
    )
    ap.add_argument(
        "--harness",
        type=Path,
        metavar="DIR",
        help="xewe-os harness: its xewe.toml gives [core] ref and [libraries]",
    )
    ap.add_argument(
        "--write-index", action="store_true", help=f"rewrite {INDEX} and exit"
    )
    args = ap.parse_args(argv)

    try:
        from xewe.modules import registry as xm
    except ImportError:
        print(
            "xewe-os-tools not importable; run with <harness>/build/tools/.venv/bin/python",
            file=sys.stderr,
        )
        return EXIT_NOT_SETUP

    core_ref, libraries = None, None
    if args.harness is not None:
        if not args.harness.is_dir():
            print(f"usage: --harness {args.harness}: not a directory", file=sys.stderr)
            return EXIT_USAGE
        try:
            core_ref, libs = read_harness(args.harness)
        except (SystemExit, tomllib.TOMLDecodeError) as exc:
            print(str(exc), file=sys.stderr)
            return EXIT_USAGE
        libraries = libs

    registry = xm.Registry.load(REPO)
    if args.write_index:
        (REPO / INDEX).write_text(render_index(registry), encoding="utf-8")
        print(f"wrote {INDEX} ({len(registry.all)} modules)")
        return EXIT_OK

    try:
        catalogue = read_catalogue()
    except tomllib.TOMLDecodeError as exc:
        print(f"{CATALOGUE}: invalid TOML: {exc}", file=sys.stderr)
        return EXIT_USAGE
    problems = list(xm.validate(registry, core_ref))
    owners = config_owners(m.slug for m in registry.all if m.slug)
    for m in registry.all:
        if (
            m.dir.parent == REPO / "modules"
        ):  # anything else is reported as stray by check_repo
            problems.extend(check_module(m, libraries, catalogue, owners))
    problems.extend(check_repo(registry))
    index = REPO / INDEX
    if not index.is_file() or index.read_text(encoding="utf-8") != render_index(
        registry
    ):
        problems.append(
            Problem(
                "repo",
                f"index: {INDEX} is out of date; run tools/validate.py --write-index",
            )
        )

    for problem in problems:
        print(str(problem))
    errors = sum(1 for x in problems if x.error)
    print(
        f"{len(registry.all)} modules, {errors} errors, {len(problems) - errors} warnings"
    )
    return EXIT_FAIL if errors else EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
